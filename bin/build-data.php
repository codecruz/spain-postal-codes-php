<?php

declare(strict_types=1);

/*
 * Regenerates resources/data.php from the spain-postal-codes dataset
 * (https://github.com/codecruz/spain-postal-codes), built from INE data.
 *
 * Usage:
 *   php bin/build-data.php                       # from the published dataset (GitHub Pages)
 *   php bin/build-data.php --from=../dataset/data   # from a local copy of data/
 */

const DEFAULT_SOURCE = 'https://codecruz.github.io/spain-postal-codes/data';
const OUTPUT = __DIR__.'/../resources/data.php';

/** @param list<string> $argv */
function main(array $argv): int
{
    $source = DEFAULT_SOURCE;
    foreach (array_slice($argv, 1) as $arg) {
        if ('--help' === $arg || '-h' === $arg) {
            fwrite(STDERR, "Usage: php bin/build-data.php [--from=<directory or URL with codigos_postales.csv, provincias.csv, metadata.json>]\n");

            return 0;
        }
        if (str_starts_with($arg, '--from=')) {
            $source = rtrim(substr($arg, 7), '/');
            continue;
        }
        fwrite(STDERR, "Unknown argument: {$arg}\n");

        return 1;
    }

    try {
        $rows = parseCsv(fetch("{$source}/codigos_postales.csv"));
        $provinces = parseCsv(fetch("{$source}/provincias.csv"));
        $meta = parseMetadata(fetch("{$source}/metadata.json"));
    } catch (Throwable $e) {
        fwrite(STDERR, "error: {$e->getMessage()}\n");

        return 1;
    }

    $provincias = [];
    foreach ($provinces as $p) {
        $provincias[$p['provincia_id']] = $p['provincia'];
    }
    if (52 !== count($provincias)) {
        fwrite(STDERR, sprintf("error: expected 52 provinces, got %d\n", count($provincias)));

        return 1;
    }

    /** @var array<string, array{string, list<string>}> $municipios */
    $municipios = [];
    foreach ($rows as $i => $row) {
        if (1 !== preg_match('/^\d{5}$/', $row['cod_postal']) || 1 !== preg_match('/^\d{5}$/', $row['municipio_id'])) {
            fwrite(STDERR, sprintf("error: invalid row %d: %s\n", $i + 2, implode(',', $row)));

            return 1;
        }
        if (!isset($provincias[substr($row['municipio_id'], 0, 2)])) {
            fwrite(STDERR, sprintf("error: unknown province in row %d\n", $i + 2));

            return 1;
        }
        $municipios[$row['municipio_id']] ??= [$row['municipio'], []];
        $municipios[$row['municipio_id']][1][] = $row['cod_postal'];
    }
    ksort($municipios, SORT_STRING);

    $out = "<?php\n\n// Generated by bin/build-data.php from the INE dataset. Do not edit.\n\nreturn [\n";
    $out .= '    \'meta\' => '.export($meta).",\n";
    $out .= '    \'provincias\' => '.export($provincias).",\n";
    $out .= "    'municipios' => [\n";
    foreach ($municipios as $id => [$nombre, $codes]) {
        sort($codes, SORT_STRING);
        $out .= sprintf("        [%s, %s, %s],\n", export((string) $id), export($nombre), export(implode(' ', array_unique($codes))));
    }
    $out .= "    ],\n];\n";

    file_put_contents(OUTPUT, $out);
    fwrite(STDERR, sprintf("resources/data.php: %d municipalities, %d postal code links, period %s (%d KB)\n", count($municipios), count($rows), $meta['period'], intdiv(strlen($out), 1024)));

    return 0;
}

function fetch(string $location): string
{
    $context = stream_context_create(['http' => ['timeout' => 60, 'user_agent' => 'spain-postal-codes-php-builder']]);
    $content = @file_get_contents($location, false, $context);
    if (false === $content) {
        throw new RuntimeException("cannot read {$location}");
    }

    return $content;
}

/**
 * @return array{period: string, referenceDate: string, source: string, license: string, attribution: string}
 */
function parseMetadata(string $json): array
{
    $metadata = json_decode($json, true, flags: JSON_THROW_ON_ERROR);
    $source = is_array($metadata) ? ($metadata['source'] ?? null) : null;
    if (!is_array($metadata) || !is_array($source)) {
        throw new UnexpectedValueException('metadata.json: missing "source" object');
    }

    $meta = [
        'period' => $source['period'] ?? null,
        'referenceDate' => $source['reference_date'] ?? null,
        'source' => $source['url'] ?? null,
        'license' => $metadata['license'] ?? null,
        'attribution' => $metadata['attribution'] ?? null,
    ];
    foreach ($meta as $key => $value) {
        if (!is_string($value) || '' === $value) {
            throw new UnexpectedValueException("metadata.json: missing or invalid value for {$key}");
        }
    }

    /** @var array{period: string, referenceDate: string, source: string, license: string, attribution: string} $meta */
    return $meta;
}

/** @return list<array<string, string>> */
function parseCsv(string $content): array
{
    $handle = fopen('php://memory', 'r+');
    if (false === $handle) {
        throw new RuntimeException('cannot open memory stream');
    }
    fwrite($handle, $content);
    rewind($handle);

    try {
        $header = fgetcsv($handle, escape: '');
        if (false === $header || in_array(null, $header, true)) {
            throw new UnexpectedValueException('CSV without a header row');
        }
        /** @var list<string> $header */
        $rows = [];
        $line = 1;
        while (false !== $values = fgetcsv($handle, escape: '')) {
            ++$line;
            if ([null] === $values) {
                continue;
            }
            if (count($values) !== count($header)) {
                throw new UnexpectedValueException(sprintf('CSV line %d: expected %d columns, got %d', $line, count($header), count($values)));
            }
            $rows[] = array_combine($header, array_map(static fn (?string $v): string => (string) $v, $values));
        }
    } finally {
        fclose($handle);
    }

    return $rows;
}

/** One-line var_export(): readable, diff-friendly and valid PHP. */
function export(mixed $value): string
{
    if (is_array($value)) {
        $items = [];
        foreach ($value as $k => $v) {
            $items[] = export((string) $k).' => '.export($v);
        }

        return '['.implode(', ', $items).']';
    }

    return var_export($value, true);
}

exit(main($argv));
